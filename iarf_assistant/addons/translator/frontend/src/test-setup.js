// jsdom does not implement HTMLDialogElement.showModal/close. Keep the
// polyfill deliberately tiny; interaction tests still exercise open/close
// state and focus restoration without pretending to be a browser renderer.
if (typeof HTMLDialogElement !== "undefined") {
  if (!HTMLDialogElement.prototype.showModal) {
    HTMLDialogElement.prototype.showModal = function showModal() {
      this.open = true;
    };
  }
  if (!HTMLDialogElement.prototype.close) {
    HTMLDialogElement.prototype.close = function close() {
      this.open = false;
      this.dispatchEvent(new Event("close"));
    };
  }
}

