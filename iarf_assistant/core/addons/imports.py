"""Explicit import support for trusted native add-ons.

The vendor finder is appended after Python's normal importers.  Add-on-local
dependencies can therefore satisfy otherwise missing imports, but can never
shadow the standard library, Carlina, or an installed application dependency.
Incompatible dependency modules across add-ons are rejected instead of being
resolved by registration order. Byte-identical artifacts may be co-owned, and
disjoint PEP 420 namespace contributions are composed: this lets separately
locked SDK distributions coexist while preserving deterministic failure for
genuinely different implementations.
"""

from __future__ import annotations

import hashlib
import importlib.abc
import importlib.machinery
import importlib.util
import json
import os
import sys
import tempfile
import threading
from collections import OrderedDict
from pathlib import Path
from types import ModuleType

INSTALLED_NAMESPACE = "_carlina_installed_addons"
VENDOR_IMPORT_INDEX_FORMAT = "carlina.vendor-import-index"
VENDOR_IMPORT_INDEX_VERSION = 1
VENDOR_IMPORT_INDEX_FILENAME = "import-index.json"
_VENDOR_IMPORT_INDEX_MAX_BYTES = 16 * 1024 * 1024


class AddonImportError(ImportError):
    """Raised when a trusted native package cannot be imported safely."""


class AddonDependencyConflict(AddonImportError):
    """Raised when in-process add-ons expose incompatible module artifacts."""


def installed_module_name(addon_id: str) -> str:
    digest = hashlib.sha256(addon_id.encode("utf-8")).hexdigest()[:16]
    return f"{INSTALLED_NAMESPACE}.addon_{digest}"


def _extension_module_name(filename: str) -> str | None:
    """Return the import name for a platform-tagged extension filename."""

    for suffix in sorted(
        importlib.machinery.EXTENSION_SUFFIXES,
        key=len,
        reverse=True,
    ):
        if filename.endswith(suffix):
            candidate = filename[: -len(suffix)]
            return candidate if candidate.isidentifier() else None
    return None


def _directory_contains_importable_code(directory: Path) -> bool:
    for candidate in directory.rglob("*"):
        if not candidate.is_file() or "__pycache__" in candidate.parts:
            continue
        if candidate.suffix == ".py" or _extension_module_name(candidate.name):
            return True
    return False


def _top_level_module_paths(lib_dir: Path) -> dict[str, Path]:
    modules: dict[str, Path] = {}
    for child in lib_dir.iterdir():
        name = child.name
        if (
            name.startswith(".")
            or name == "__pycache__"
            or name.endswith((".dist-info", ".egg-info"))
        ):
            continue
        module_name: str | None = None
        if child.is_file() and child.suffix == ".py":
            module_name = child.stem if child.stem.isidentifier() else None
        elif child.is_file():
            module_name = _extension_module_name(name)
        elif (
            child.is_dir()
            and name.isidentifier()
            and _directory_contains_importable_code(child)
            and importlib.machinery.PathFinder.find_spec(name, [str(lib_dir)])
        ):
            # PEP 420 namespace packages intentionally have no __init__.py.
            # PathFinder is the authoritative check for whether the directory
            # can participate in a top-level import from this vendor root.
            module_name = name
        if module_name is not None:
            modules[module_name] = child
    return modules


def _top_level_modules(lib_dir: Path) -> set[str]:
    """Return importable names, including normalized native extensions."""

    return set(_top_level_module_paths(lib_dir))


def _module_artifact_digest(path: Path) -> str:
    """Hash one import artifact while ignoring generated bytecode caches."""

    digest = hashlib.sha256()
    if path.is_file():
        files = ((path.name, path),)
    else:
        files = tuple(
            (candidate.relative_to(path).as_posix(), candidate)
            for candidate in sorted(path.rglob("*"))
            if candidate.is_file()
            and "__pycache__" not in candidate.parts
            and candidate.suffix not in {".pyc", ".pyo"}
        )
    for relative_name, candidate in files:
        digest.update(relative_name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(candidate.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def _is_namespace_package_artifact(path: Path) -> bool:
    return path.is_dir() and not (path / "__init__.py").is_file()


def _namespace_import_artifacts(path: Path) -> dict[str, tuple[str, str]]:
    """Index import identities below one PEP 420 namespace contribution."""

    artifacts: dict[str, tuple[str, str]] = {}

    def visit(directory: Path, parts: tuple[str, ...]) -> None:
        initializer = directory / "__init__.py"
        if parts and initializer.is_file():
            artifacts[".".join(parts)] = (
                "package",
                _module_artifact_digest(directory),
            )
            return

        for child in sorted(directory.iterdir(), key=lambda item: item.name):
            if child.name == "__pycache__" or child.name.startswith("."):
                continue
            if child.is_dir():
                if child.name.isidentifier():
                    visit(child, (*parts, child.name))
                continue
            if not child.is_file() or child.suffix in {".pyc", ".pyo"}:
                continue

            module_name: str | None = None
            if child.suffix == ".py" and child.stem != "__init__":
                module_name = child.stem if child.stem.isidentifier() else None
            elif child.suffix != ".py":
                module_name = _extension_module_name(child.name)
            if module_name is not None:
                artifacts[".".join((*parts, module_name))] = (
                    "module",
                    _module_artifact_digest(child),
                )
                continue

            relative_name = child.relative_to(path).as_posix()
            artifacts[f"resource:{relative_name}"] = (
                "resource",
                _module_artifact_digest(child),
            )

    visit(path, ())
    return artifacts


def _namespace_artifact_indexes_are_compatible(
    first_artifacts: dict[str, tuple[str, str]],
    second_artifacts: dict[str, tuple[str, str]],
) -> bool:
    """Return whether two namespace indexes compose without import ambiguity."""
    for identity in first_artifacts.keys() & second_artifacts.keys():
        if first_artifacts[identity] != second_artifacts[identity]:
            return False

    first_modules = {
        key for key, value in first_artifacts.items() if value[0] != "resource"
    }
    second_modules = {
        key for key, value in second_artifacts.items() if value[0] != "resource"
    }
    for module_name in first_modules:
        parts = module_name.split(".")
        if any(".".join(parts[:index]) in second_modules for index in range(1, len(parts))):
            return False
    for module_name in second_modules:
        parts = module_name.split(".")
        if any(".".join(parts[:index]) in first_modules for index in range(1, len(parts))):
            return False
    return True


def _valid_sha256(value: object) -> bool:
    normalized = str(value or "").lower()
    return len(normalized) == 64 and all(
        character in "0123456789abcdef" for character in normalized
    )


def _environment_marker_sha256(lib_dir: Path) -> str | None:
    marker = lib_dir.parent / "environment.json"
    try:
        marker_bytes = marker.read_bytes()
    except OSError:
        return None
    return hashlib.sha256(marker_bytes).hexdigest()


def _load_vendor_import_index(
    lib_dir: Path,
) -> tuple[
    dict[str, Path],
    dict[Path, str],
    dict[Path, dict[str, tuple[str, str]]],
] | None:
    """Load a bounded index tied to one immutable environment marker."""

    resolved = lib_dir.resolve()
    index_path = resolved.parent / VENDOR_IMPORT_INDEX_FILENAME
    marker_sha256 = _environment_marker_sha256(resolved)
    if marker_sha256 is None:
        return None
    try:
        if index_path.stat().st_size > _VENDOR_IMPORT_INDEX_MAX_BYTES:
            return None
        payload = json.loads(index_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError):
        return None
    if not isinstance(payload, dict):
        return None
    if (
        payload.get("format") != VENDOR_IMPORT_INDEX_FORMAT
        or payload.get("version") != VENDOR_IMPORT_INDEX_VERSION
        or payload.get("environment_marker_sha256") != marker_sha256
    ):
        return None

    raw_modules = payload.get("modules")
    if not isinstance(raw_modules, dict) or len(raw_modules) > 10_000:
        return None
    modules: dict[str, Path] = {}
    digests: dict[Path, str] = {}
    namespace_indexes: dict[Path, dict[str, tuple[str, str]]] = {}
    for module_name, raw_entry in raw_modules.items():
        if not (
            isinstance(module_name, str)
            and module_name.isidentifier()
            and isinstance(raw_entry, dict)
        ):
            return None
        relative_path = Path(str(raw_entry.get("path") or ""))
        if (
            relative_path.is_absolute()
            or len(relative_path.parts) != 1
            or relative_path.name in {"", ".", ".."}
        ):
            return None
        artifact = (resolved / relative_path).resolve()
        try:
            artifact.relative_to(resolved)
        except ValueError:
            return None
        if artifact.parent != resolved or not artifact.exists():
            return None

        entry_type = raw_entry.get("type")
        if entry_type == "artifact":
            digest = raw_entry.get("digest")
            if not _valid_sha256(digest):
                return None
            digests[artifact] = str(digest).lower()
        elif entry_type == "namespace":
            raw_artifacts = raw_entry.get("artifacts")
            if not isinstance(raw_artifacts, dict) or len(raw_artifacts) > 100_000:
                return None
            namespace_artifacts: dict[str, tuple[str, str]] = {}
            for identity, raw_identity in raw_artifacts.items():
                if not (
                    isinstance(identity, str)
                    and identity
                    and isinstance(raw_identity, list)
                    and len(raw_identity) == 2
                    and raw_identity[0] in {"package", "module", "resource"}
                    and _valid_sha256(raw_identity[1])
                ):
                    return None
                namespace_artifacts[identity] = (
                    str(raw_identity[0]),
                    str(raw_identity[1]).lower(),
                )
            namespace_indexes[artifact] = namespace_artifacts
        else:
            return None
        modules[module_name] = artifact
    return modules, digests, namespace_indexes


def build_vendor_import_index(lib_dir: str | Path) -> Path:
    """Hash one immutable vendor tree once for fast, safe runtime registration."""

    resolved = Path(lib_dir).resolve()
    marker_sha256 = _environment_marker_sha256(resolved)
    if marker_sha256 is None:
        raise ValueError(
            f"Vendor dependency environment has no marker: {resolved.parent}"
        )
    modules = _top_level_module_paths(resolved)
    encoded_modules: dict[str, dict[str, object]] = {}
    for module_name, artifact in sorted(modules.items()):
        relative_path = artifact.relative_to(resolved).as_posix()
        if _is_namespace_package_artifact(artifact):
            encoded_modules[module_name] = {
                "path": relative_path,
                "type": "namespace",
                "artifacts": {
                    identity: list(value)
                    for identity, value in sorted(
                        _namespace_import_artifacts(artifact).items()
                    )
                },
            }
        else:
            encoded_modules[module_name] = {
                "path": relative_path,
                "type": "artifact",
                "digest": _module_artifact_digest(artifact),
            }

    payload = {
        "format": VENDOR_IMPORT_INDEX_FORMAT,
        "version": VENDOR_IMPORT_INDEX_VERSION,
        "environment_marker_sha256": marker_sha256,
        "modules": encoded_modules,
    }
    index_path = resolved.parent / VENDOR_IMPORT_INDEX_FILENAME
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=index_path.parent,
            # Keep this name shorter than the final file. Windows dependency
            # generations deliberately run close to conservative path limits.
            prefix=".i",
            suffix="",
            delete=False,
        ) as handle:
            temporary_path = Path(handle.name)
            json.dump(payload, handle, ensure_ascii=True, sort_keys=True)
            handle.write("\n")
        os.replace(temporary_path, index_path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    return index_path


def prepare_vendor_import_index(lib_dir: str | Path) -> bool:
    """Create a missing/stale immutable import index; return whether it changed."""

    resolved = Path(lib_dir).resolve()
    if _load_vendor_import_index(resolved) is not None:
        return False
    build_vendor_import_index(resolved)
    return True


def _resolved_module_spec(
    module_name: str,
) -> importlib.machinery.ModuleSpec | None:
    """Return the first ordinary import spec for one top-level module."""

    return next(
        (
            spec
            for finder in (
                importlib.machinery.BuiltinImporter,
                importlib.machinery.FrozenImporter,
                importlib.machinery.PathFinder,
            )
            if (spec := finder.find_spec(module_name)) is not None
        ),
        None,
    )


def _resolved_before_vendor_finder(module_name: str) -> bool:
    """Return whether Python's ordinary importers already provide the name."""

    return _resolved_module_spec(module_name) is not None


def _host_namespace_paths(module_name: str) -> tuple[Path, ...]:
    """Return ordinary PEP 420 search locations for one top-level module."""

    spec = _resolved_module_spec(module_name)
    locations = getattr(spec, "submodule_search_locations", None)
    if spec is None or spec.loader is not None or locations is None:
        return ()
    return tuple(Path(location).resolve() for location in locations)


class AddonVendorFinder(importlib.abc.MetaPathFinder):
    """Last-chance finder for non-shadowing add-on dependency directories."""

    def __init__(self) -> None:
        self._paths: OrderedDict[str, Path] = OrderedDict()
        self._providers: dict[str, OrderedDict[str, Path]] = {}
        self._artifact_digests: dict[Path, str] = {}
        self._namespace_artifact_indexes: dict[
            Path, dict[str, tuple[str, str]]
        ] = {}
        self._managed_namespace_modules: set[str] = set()
        self._lock = threading.RLock()

    def _digest(self, artifact: Path) -> str:
        digest = self._artifact_digests.get(artifact)
        if digest is None:
            digest = _module_artifact_digest(artifact)
            self._artifact_digests[artifact] = digest
        return digest

    def _namespace_index(self, artifact: Path) -> dict[str, tuple[str, str]]:
        index = self._namespace_artifact_indexes.get(artifact)
        if index is None:
            index = _namespace_import_artifacts(artifact)
            self._namespace_artifact_indexes[artifact] = index
        return index

    def _compatible_artifacts(self, first: Path, second: Path) -> bool:
        first_is_namespace = _is_namespace_package_artifact(first)
        second_is_namespace = _is_namespace_package_artifact(second)
        if first_is_namespace or second_is_namespace:
            return (
                first_is_namespace
                and second_is_namespace
                and _namespace_artifact_indexes_are_compatible(
                    self._namespace_index(first),
                    self._namespace_index(second),
                )
            )
        return self._digest(first) == self._digest(second)

    def _namespace_provider_paths(self, module_name: str) -> list[Path]:
        providers = self._providers.get(module_name)
        if not providers or not all(
            _is_namespace_package_artifact(path) for path in providers.values()
        ):
            return []
        return list(providers.values())

    def _namespace_search_paths(self, module_name: str) -> list[Path]:
        """Return host and vendor paths in deterministic import order."""

        paths = list(_host_namespace_paths(module_name))
        for path in self._namespace_provider_paths(module_name):
            if path not in paths:
                paths.append(path)
        return paths

    def _ensure_host_namespace_loaded(self, module_name: str) -> None:
        """Load an ordinary namespace before attaching vendor search paths."""

        if module_name not in sys.modules and _host_namespace_paths(module_name):
            importlib.import_module(module_name)

    def _refresh_loaded_namespace(self, module_name: str) -> None:
        if module_name not in self._managed_namespace_modules:
            return
        module = sys.modules.get(module_name)
        if module is None or getattr(module, "__file__", None) is not None:
            return
        locations = [str(path) for path in self._namespace_search_paths(module_name)]
        module.__path__ = locations
        spec = getattr(module, "__spec__", None)
        if spec is not None:
            spec.submodule_search_locations = locations

    def _drop_cached_artifact(self, artifact: Path) -> None:
        for cached_path in tuple(self._artifact_digests):
            if cached_path == artifact or cached_path.is_relative_to(artifact):
                self._artifact_digests.pop(cached_path, None)
        for cached_path in tuple(self._namespace_artifact_indexes):
            if cached_path == artifact or cached_path.is_relative_to(artifact):
                self._namespace_artifact_indexes.pop(cached_path, None)

    def register(self, addon_id: str, lib_dir: str | Path) -> None:
        resolved = Path(lib_dir).resolve()
        if not resolved.is_dir():
            return
        indexed = _load_vendor_import_index(resolved)
        if indexed is None:
            indexed_modules = _top_level_module_paths(resolved)
            indexed_digests: dict[Path, str] = {}
            indexed_namespaces: dict[
                Path, dict[str, tuple[str, str]]
            ] = {}
        else:
            indexed_modules, indexed_digests, indexed_namespaces = indexed
        # The finder is deliberately last in sys.meta_path. Artifacts already
        # supplied by Python or the application environment can never be
        # selected from a vendor root, so they do not participate in fallback
        # ownership or conflicts.
        host_namespace_paths = {
            module_name: _host_namespace_paths(module_name)
            for module_name in indexed_modules
        }
        namespace_indexes = dict(indexed_namespaces)
        modules = {}
        for module_name, artifact in indexed_modules.items():
            host_paths = host_namespace_paths[module_name]
            if host_paths:
                if not _is_namespace_package_artifact(artifact):
                    continue
                vendor_index = namespace_indexes.get(artifact)
                if vendor_index is None:
                    vendor_index = _namespace_import_artifacts(artifact)
                    namespace_indexes[artifact] = vendor_index
                host_indexes = []
                for host_path in host_paths:
                    host_index = namespace_indexes.get(host_path)
                    if host_index is None:
                        host_index = _namespace_import_artifacts(host_path)
                        namespace_indexes[host_path] = host_index
                    host_indexes.append(host_index)
                if any(
                    not _namespace_artifact_indexes_are_compatible(
                        host_index,
                        vendor_index,
                    )
                    for host_index in host_indexes
                ):
                    raise AddonDependencyConflict(
                        f"Add-on '{addon_id}' provides an incompatible contribution "
                        f"to host namespace '{module_name}'. Align the locked "
                        "dependency versions or isolate the add-on environment."
                    )
                modules[module_name] = artifact
            elif not _resolved_before_vendor_finder(module_name):
                modules[module_name] = artifact
        with self._lock:
            # A development source can be re-registered at the same path. Do
            # not retain a stale digest for its prior contents.
            for providers in self._providers.values():
                previous = providers.get(addon_id)
                if previous is not None:
                    self._drop_cached_artifact(previous)

            self._artifact_digests.update(indexed_digests)
            self._namespace_artifact_indexes.update(namespace_indexes)
            for module_name, artifact in sorted(modules.items()):
                providers = self._providers.get(module_name, {})
                for owner, existing_artifact in providers.items():
                    if owner == addon_id or existing_artifact == artifact:
                        continue
                    if not self._compatible_artifacts(existing_artifact, artifact):
                        raise AddonDependencyConflict(
                            f"Add-ons '{owner}' and '{addon_id}' provide incompatible "
                            f"top-level module '{module_name}'. Use an isolated worker "
                            "environment or align their locked dependency versions."
                        )
            self.unregister(addon_id)
            self._artifact_digests.update(indexed_digests)
            self._namespace_artifact_indexes.update(namespace_indexes)
            self._paths[addon_id] = resolved
            for module_name, artifact in modules.items():
                self._providers.setdefault(module_name, OrderedDict())[addon_id] = (
                    artifact
                )
                if host_namespace_paths[module_name]:
                    self._managed_namespace_modules.add(module_name)
                    self._ensure_host_namespace_loaded(module_name)
                self._refresh_loaded_namespace(module_name)

    def unregister(self, addon_id: str) -> None:
        with self._lock:
            self._paths.pop(addon_id, None)
            for module_name, providers in tuple(self._providers.items()):
                artifact = providers.pop(addon_id, None)
                if artifact is not None:
                    self._drop_cached_artifact(artifact)
                if not providers:
                    self._providers.pop(module_name, None)
                self._refresh_loaded_namespace(module_name)

    def registered_paths(self) -> dict[str, Path]:
        with self._lock:
            return dict(self._paths)

    def find_spec(self, fullname, path=None, target=None):
        del target
        if path is not None:
            return None
        top_level = str(fullname).partition(".")[0]
        with self._lock:
            providers = self._providers.get(top_level)
            namespace_paths = self._namespace_provider_paths(top_level)
            owner = next(iter(providers), None) if providers else None
            lib_dir = self._paths.get(owner) if owner is not None else None
            if namespace_paths:
                self._managed_namespace_modules.add(top_level)
        if lib_dir is None:
            return None
        if namespace_paths:
            search_roots = [
                str(path.parent) for path in self._namespace_search_paths(top_level)
            ]
            return importlib.machinery.PathFinder.find_spec(fullname, search_roots)
        return importlib.machinery.PathFinder.find_spec(fullname, [str(lib_dir)])


_VENDOR_FINDER = AddonVendorFinder()


def vendor_finder() -> AddonVendorFinder:
    if _VENDOR_FINDER not in sys.meta_path:
        sys.meta_path.append(_VENDOR_FINDER)
    return _VENDOR_FINDER


def _ensure_installed_namespace() -> None:
    if INSTALLED_NAMESPACE in sys.modules:
        return
    namespace = ModuleType(INSTALLED_NAMESPACE)
    namespace.__package__ = INSTALLED_NAMESPACE
    namespace.__path__ = []
    namespace.__spec__ = importlib.machinery.ModuleSpec(
        INSTALLED_NAMESPACE,
        loader=None,
        is_package=True,
    )
    sys.modules[INSTALLED_NAMESPACE] = namespace


def load_installed_addon_module(addon_id: str, addon_dir: str | Path):
    """Load one approved installed package under a non-shadowing namespace."""

    resolved_dir = Path(addon_dir).resolve()
    entry_file = resolved_dir / "__init__.py"
    if not entry_file.is_file():
        raise AddonImportError(
            f"Installed native add-on '{addon_id}' is missing __init__.py."
        )
    _ensure_installed_namespace()
    module_name = installed_module_name(addon_id)
    existing = sys.modules.get(module_name)
    if existing is not None:
        existing_file = Path(str(getattr(existing, "__file__", ""))).resolve()
        if existing_file == entry_file:
            return existing
        raise AddonImportError(
            f"Installed module namespace for '{addon_id}' is already bound to "
            f"{existing_file}."
        )

    spec = importlib.util.spec_from_file_location(
        module_name,
        entry_file,
        submodule_search_locations=[str(resolved_dir)],
    )
    if spec is None or spec.loader is None:
        raise AddonImportError(f"Could not create an import spec for '{addon_id}'.")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        unload_installed_addon_module(addon_id)
        raise
    return module


def unload_installed_addon_module(addon_id: str) -> None:
    prefix = installed_module_name(addon_id)
    for module_name in [
        name for name in tuple(sys.modules) if name == prefix or name.startswith(f"{prefix}.")
    ]:
        sys.modules.pop(module_name, None)


